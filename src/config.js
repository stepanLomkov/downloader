/**
 * Централизованная конфигурация скрипта.
 *
 * Все «магические числа» и строки собраны в одном месте,
 * чтобы их можно было менять без правки логики в других модулях.
 */

/**
 * Сколько запросов делать по умолчанию,
 * если пользователь не передал второй аргумент N.
 */
export const DEFAULT_N = 10;

/**
 * Максимальное число редиректов, которое разрешено пройти
 * в рамках одного измерения. Защита от бесконечного цикла.
 */
export const MAX_REDIRECTS = 5;

/**
 * Заголовок User-Agent, который отправляем серверу.
 * Позволяет в логах сервера отличать наш скрипт от браузера.
 */
export const USER_AGENT = 'node-download/1.0';

/**
 * Минимальный интервал (мс) между перерисовками live-прогресс-бара.
 * Без этого ограничения на быстрых соединениях
 * process.stdout.write вызывается тысячи раз в секунду и ест CPU.
 */
export const LIVE_REFRESH_MS = 100;

/**
 * Код выхода при некорректных аргументах командной строки.
 * Совпадает с тем, что делают большинство unix-утилит для «usage error».
 */
export const EXIT_BAD_ARGS = 2;

/**
 * Код выхода при фатальной ошибке времени выполнения.
 */
export const EXIT_FATAL = 1;

/**
 * Код выхода при прерывании через Ctrl+C.
 * 130 = 128 + SIGINT, стандарт POSIX.
 */
export const EXIT_INTERRUPTED = 130;

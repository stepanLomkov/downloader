/**
 * ANSI-коды, цветовые хелперы и последовательности для работы с терминалом.
 *
 * Все хелперы идемпотентны по отношению к окружению:
 * если цвета отключены, они возвращают строку без изменений.
 */

/**
 * Является ли stdout терминалом (а не файлом/пайпом).
 * Если нет — не сыпем escape-последовательностями и не рисуем live-бар.
 */
export const isTTY = !!process.stdout.isTTY;

/**
 * Должны ли мы использовать цвета.
 * Уважаем переменную NO_COLOR (см. https://no-color.org):
 * сам факт её наличия (даже пустая строка) отключает цвет.
 */
export const useColor = isTTY && !('NO_COLOR' in process.env);

/**
 * Собирает ANSI escape-последовательность из числового кода.
 * 1 = bold, 2 = dim, 31 = красный, 32 = зелёный, 33 = жёлтый, 36 = голубой.
 */
const esc = code => `\x1b[${code}m`;

/**
 * Оборачивает строку в ANSI-код, если цвета включены.
 * В противном случае возвращает строку как есть.
 *
 * @param {number} code — SGR-код (1, 2, 31, …)
 * @param {string} s    — текст
 * @returns {string}
 */
export const colorize = (code, s) => (useColor ? `${esc(code)}${s}${esc(0)}` : s);

/** Приглушённый (серый) текст — для подписей и второстепенной инфы. */
export const dim = s => colorize(2, s);

/** Жирный текст — для заголовков и акцентов. */
export const bold = s => colorize(1, s);

/** Зелёный — для успешного статуса 200. */
export const green = s => colorize(32, s);

/** Жёлтый — для предупреждений (например, несовпадение Content-Length). */
export const yellow = s => colorize(33, s);

/** Красный — для ошибок и неуспешных статусов. */
export const red = s => colorize(31, s);

/** Голубой — для динамических значений (скорость в live-баре). */
export const cyan = s => colorize(36, s);

/**
 * Полностью очищает текущую строку и возвращает курсор в начало.
 * Используется для перерисовки live-прогресс-бара.
 */
export const CLEAR_LINE = '\x1b[2K\r';

/**
 * Скрывает курсор — чтобы он не мигал во время работы прогресс-бара.
 * Восстанавливается через SHOW_CURSOR (в т.ч. при Ctrl+C).
 */
export const HIDE_CURSOR = '\x1b[?25l';

/** Показывает курсор обратно. */
export const SHOW_CURSOR = '\x1b[?25h';
